export const frameworkUnits: Record<string, FrameworkUnitSpec[]> = rawUnits;

export function getFrameworkUnit(frameworkId: string, unitNumber: number): FrameworkUnitSpec | null {
  const list = frameworkUnits[frameworkId];
  if (!list) return null;
  return list.find((u) => u.unit === unitNumber) || null;
}
